export const AIRLINES = RAW.map(([code, name]) => ({ code, name }));

const BY_CODE = new Map(AIRLINES.map((a) => [a.code, a]));

export const airlineName = (code) => BY_CODE.get(String(code || '').trim().toUpperCase())?.name || '';

export const searchAirlines = (query, limit = 12) => {
  const q = String(query || '').trim().toUpperCase();
  if (!q) return AIRLINES.slice(0, limit);
  const scored = [];
  for (const airline of AIRLINES) {
    const name = airline.name.toUpperCase();
    let score = null;
    if (airline.code === q) score = 0;
    else if (name.startsWith(q)) score = 1;
    else if (airline.code.startsWith(q)) score = 2;
    else if (name.includes(q)) score = 3;
    if (score === null) continue;
    scored.push([score, airline]);
  }
  return scored.sort((a, b) => a[0] - b[0] || a[1].name.localeCompare(b[1].name))
    .slice(0, limit)
    .map(([, a]) => a);
};
